// ===== JSON Export =====

/** Serialize a plan to a JSON string for download. */
export function generatePlanJSON(plan: Plan): string {
  return JSON.stringify(plan, null, 2);
}

// ===== Text Summary for copy/WhatsApp =====

/** Generate a plain-text summary suitable for WhatsApp sharing. */
export function generateTextSummary(plan: Plan): string {
  const { input, summary, budget, timeline, tips } = plan;
  const totalPlanned = budget.reduce((s, i) => s + i.planned, 0);
  const currency = input.currency;

  const budgetLines = budget
    .slice(0, 8)
    .map((b) => `  • ${b.category}: ${formatMoney(b.planned, currency)}`)
    .join("\n");

  const upcomingTasks = timeline
    .filter((t) => !t.done)
    .slice(0, 5)
    .map((t) => `  • [${t.date}] ${t.task}`)
    .join("\n");

  const tipsText = tips
    .slice(0, 3)
    .map((t) => `  • ${t}`)
    .join("\n");

  return [
    `🎉 *${input.name}* — ${input.eventType.charAt(0).toUpperCase() + input.eventType.slice(1)} Plan`,
    `📅 Date: ${input.date}  📍 ${input.city}`,
    `👥 Guests: ${input.guests}  💰 Budget: ${formatMoney(totalPlanned, currency)}`,
    "",
    `📝 Summary:\n${summary}`,
    "",
    `💰 Budget Breakdown:\n${budgetLines}`,
    "",
    `📋 Upcoming Tasks:\n${upcomingTasks}`,
    "",
    `💡 Tips:\n${tipsText}`,
    "",
    "---",
    "Generated by Jashn — AI Event Planner",
  ].join("\n");
}

// ===== Trigger download in browser =====

/** Trigger a file download from a string blob. */
export function triggerDownload(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
