// ===== CSV Export =====

/** Generate a budget CSV string with injection protection. */
export function generateBudgetCSV(budget: Budget, currency: string): string {
  const headers = ["Category", "Planned", "Actual", "Remaining", "Notes"].join(",");
  const rows = budget.map((item) => {
    const remaining = item.planned - item.actual;
    return [
      `"${guardCsvCell(item.category)}"`,
      item.planned.toFixed(2),
      item.actual.toFixed(2),
      remaining.toFixed(2),
      `"${guardCsvCell(item.notes)}"`,
    ].join(",");
  });
  const totalPlanned = budget.reduce((s, i) => s + i.planned, 0);
  const totalActual = budget.reduce((s, i) => s + i.actual, 0);
  const totalRow = [
    '"TOTAL"',
    totalPlanned.toFixed(2),
    totalActual.toFixed(2),
    (totalPlanned - totalActual).toFixed(2),
    `"Currency: ${guardCsvCell(currency)}"`,
  ].join(",");

  return [headers, ...rows, totalRow].join("\r\n");
}

